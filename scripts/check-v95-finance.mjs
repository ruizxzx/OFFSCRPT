import fs from 'node:fs';
import path from 'node:path';
const root=process.cwd();
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const checks=[]; const req=(label,ok)=>checks.push([label,Boolean(ok)]);
const pkg=JSON.parse(read('package.json'));
req('version is V95+ compatible',/^0\.(?:9[6-9]|[1-9]\d)\.\d+$/.test(pkg.version));
req('finance admin component',fs.existsSync(path.join(root,'src/components/FinanceAdminPanel.tsx')));
const comp=read('src/components/FinanceAdminPanel.tsx');
const api=read('api/commerce/index.ts');
const lib=read('src/lib/commerce.ts');
const admin=read('src/components/CommerceAdminPanel.tsx');
req('finance summary API',api.includes("action==='getFinanceSummary'"));
req('revenue series API',api.includes("action==='getRevenueSeries'"));
req('creator finance API',api.includes("action==='getCreatorFinance'"));
req('product finance API',api.includes("action==='getProductFinance'"));
req('order finance API',api.includes("action==='getOrderFinance'"));
req('payout finance API',api.includes("action==='getPayoutFinance'"));
req('refund finance API',api.includes("action==='getRefundFinance'"));
req('finance health API',api.includes("action==='getFinanceHealth'"));
req('finance export API',api.includes("action==='exportFinance'"));
req('server-side finance authorization',api.includes("Finance administrator access required."));
req('canonical V93/V94 sources',api.includes('commerceFinancialAllocations')&&api.includes('commerceVendorLedger')&&api.includes('creatorPayouts'));
req('integer paise reporting',api.includes('v95Paise')&&api.includes('grossSalesPaise'));
req('date range validation',api.includes('v95ReportWindow')&&api.includes('INVALID_DATE_RANGE'));
req('comparison periods',api.includes('v95PreviousWindow')&&api.includes('v95PercentChange'));
req('reconciliation health',api.includes('v95FinanceHealth')&&api.includes('duplicate_transfer_id'));
req('CSV export',api.includes('v95CsvEscape')&&api.includes('filename'));
req('no direct V95 payout execution',!api.includes("action==='financeCreatePayout'"));
req('client finance API wrappers',lib.includes('getFinanceReport')&&lib.includes('exportFinanceCsv'));
req('admin integration',admin.includes('<FinanceAdminPanel />'));
req('finance sections',comp.includes('Finance Intelligence')&&comp.includes('Revenue Trend')&&comp.includes('Finance Health'));
req('creator/product/order drilldown',comp.includes("dimension==='creator'")||comp.includes("'creator','product','order'"));
const failed=checks.filter(([,ok])=>!ok);
for(const [label,ok] of checks) console.log(`${ok?'PASS':'FAIL'} ${label}`);
if(failed.length) { console.error(`V95 validation failed: ${failed.length}/${checks.length}`); process.exit(1); }
console.log(`V95 validation passed: ${checks.length}/${checks.length}`);
